-- Schéma Duelo (SQLite WAL). Voir §7.3 du cahier des charges.
PRAGMA journal_mode=WAL;

CREATE TABLE IF NOT EXISTS users(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT NOT NULL UNIQUE COLLATE NOCASE,
  password_hash TEXT NOT NULL,
  email TEXT NULL,
  role TEXT NOT NULL DEFAULT 'user',           -- user|admin|guest
  avatar INTEGER NOT NULL DEFAULT 1,           -- 1..24
  frame TEXT NOT NULL DEFAULT 'base',
  title TEXT NOT NULL DEFAULT '',
  xp INTEGER NOT NULL DEFAULT 0, level INTEGER NOT NULL DEFAULT 1,
  coins INTEGER NOT NULL DEFAULT 0,
  elo INTEGER NOT NULL DEFAULT 1000, elo_games INTEGER NOT NULL DEFAULT 0,
  streak_days INTEGER NOT NULL DEFAULT 0, best_streak INTEGER NOT NULL DEFAULT 0,
  freeze_tokens INTEGER NOT NULL DEFAULT 0,
  last_login_day TEXT NULL, last_chest_day TEXT NULL,
  coins_day TEXT NULL, coins_day_amount INTEGER NOT NULL DEFAULT 0,
  daily_streak_frozen TEXT NULL DEFAULT '0',
  created_at INTEGER NOT NULL, last_seen_at INTEGER NOT NULL, status TEXT NOT NULL DEFAULT 'active',
  age_ok INTEGER NOT NULL DEFAULT 1, referrer_id INTEGER NULL, guest_duels INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_users_elo ON users(elo DESC);
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);

CREATE TABLE IF NOT EXISTS recovery_codes(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, code_hash TEXT NOT NULL, used_at INTEGER NULL);
CREATE TABLE IF NOT EXISTS sessions(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, token_hash TEXT NOT NULL UNIQUE, created_at INTEGER NOT NULL, expires_at INTEGER NOT NULL, user_agent TEXT NULL);

CREATE TABLE IF NOT EXISTS friends(user_id INTEGER NOT NULL, friend_id INTEGER NOT NULL, status TEXT NOT NULL DEFAULT 'pending', created_at INTEGER NOT NULL, PRIMARY KEY(user_id, friend_id));

CREATE TABLE IF NOT EXISTS categories(id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT UNIQUE NOT NULL, label TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS questions(
  id INTEGER PRIMARY KEY AUTOINCREMENT, category_id INTEGER NOT NULL, difficulty INTEGER NOT NULL,
  text TEXT NOT NULL, a TEXT NOT NULL, b TEXT NOT NULL, c TEXT NOT NULL, d TEXT NOT NULL,
  correct INTEGER NOT NULL, source TEXT NOT NULL DEFAULT '', verified INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'live', author_id INTEGER NULL,
  times_asked INTEGER NOT NULL DEFAULT 0, times_correct INTEGER NOT NULL DEFAULT 0, created_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_q_catdiff ON questions(category_id, difficulty, status);

CREATE TABLE IF NOT EXISTS question_votes(question_id INTEGER NOT NULL, user_id INTEGER NOT NULL, vote TEXT NOT NULL, created_at INTEGER NOT NULL, PRIMARY KEY(question_id, user_id));
CREATE TABLE IF NOT EXISTS question_reports(id INTEGER PRIMARY KEY AUTOINCREMENT, question_id INTEGER NOT NULL, user_id INTEGER NOT NULL, reason TEXT NOT NULL, created_at INTEGER NOT NULL, handled INTEGER NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS duels(
  id INTEGER PRIMARY KEY AUTOINCREMENT, mode TEXT NOT NULL DEFAULT 'ranked', status TEXT NOT NULL DEFAULT 'waiting',
  player1_id INTEGER NOT NULL, player2_id INTEGER NOT NULL, is_ghost INTEGER NOT NULL DEFAULT 0,
  score1 INTEGER NOT NULL DEFAULT 0, score2 INTEGER NOT NULL DEFAULT 0, winner_id INTEGER NULL,
  elo_delta1 INTEGER NOT NULL DEFAULT 0, elo_delta2 INTEGER NOT NULL DEFAULT 0,
  tournament_match_id INTEGER NULL, flagged INTEGER NOT NULL DEFAULT 0,
  started_at INTEGER NULL, ended_at INTEGER NULL, rematch_of INTEGER NULL
);
CREATE INDEX IF NOT EXISTS idx_duels_p1 ON duels(player1_id, ended_at);
CREATE INDEX IF NOT EXISTS idx_duels_p2 ON duels(player2_id, ended_at);

CREATE TABLE IF NOT EXISTS duel_answers(duel_id INTEGER NOT NULL, round INTEGER NOT NULL, user_id INTEGER NOT NULL, answer INTEGER NULL, correct INTEGER NOT NULL DEFAULT 0, time_ms INTEGER NOT NULL DEFAULT 0, points INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(duel_id, round, user_id));
CREATE TABLE IF NOT EXISTS duel_seen(user_id INTEGER NOT NULL, question_id INTEGER NOT NULL, seen_at INTEGER NOT NULL, PRIMARY KEY(user_id, question_id));

CREATE TABLE IF NOT EXISTS reward_ledger(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, kind TEXT NOT NULL, amount_coins INTEGER NOT NULL DEFAULT 0, amount_xp INTEGER NOT NULL DEFAULT 0, ref_type TEXT NULL, ref_id INTEGER NULL, created_at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS idx_ledger_user ON reward_ledger(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS badges(id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT UNIQUE NOT NULL, label TEXT NOT NULL, rarity TEXT NOT NULL DEFAULT 'commun', condition_json TEXT NOT NULL DEFAULT '{}');
CREATE TABLE IF NOT EXISTS user_badges(user_id INTEGER NOT NULL, badge_id INTEGER NOT NULL, earned_at INTEGER NOT NULL, PRIMARY KEY(user_id, badge_id));
CREATE TABLE IF NOT EXISTS cosmetics(id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT UNIQUE NOT NULL, type TEXT NOT NULL, price INTEGER NOT NULL DEFAULT 0, rarity TEXT NOT NULL DEFAULT 'commun', label TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS user_cosmetics(user_id INTEGER NOT NULL, cosmetic_id INTEGER NOT NULL, acquired_at INTEGER NOT NULL, PRIMARY KEY(user_id, cosmetic_id));

CREATE TABLE IF NOT EXISTS challenges(id INTEGER PRIMARY KEY AUTOINCREMENT, scope TEXT NOT NULL, code TEXT NOT NULL, goal INTEGER NOT NULL DEFAULT 1, reward_coins INTEGER NOT NULL DEFAULT 0, reward_xp INTEGER NOT NULL DEFAULT 0, label TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS user_challenges(user_id INTEGER NOT NULL, challenge_id INTEGER NOT NULL, period_key TEXT NOT NULL, progress INTEGER NOT NULL DEFAULT 0, claimed_at INTEGER NULL, PRIMARY KEY(user_id, challenge_id, period_key));
CREATE TABLE IF NOT EXISTS daily_runs(id INTEGER PRIMARY KEY AUTOINCREMENT, period_key TEXT NOT NULL, user_id INTEGER NOT NULL, score INTEGER NOT NULL DEFAULT 0, total_time_ms INTEGER NOT NULL DEFAULT 0, finished_at INTEGER NULL, answers_json TEXT NULL DEFAULT '[]');
CREATE UNIQUE INDEX IF NOT EXISTS idx_dailyrun_user_period ON daily_runs(period_key, user_id);

CREATE TABLE IF NOT EXISTS friend_challenges(id INTEGER PRIMARY KEY AUTOINCREMENT, from_id INTEGER NOT NULL, to_id INTEGER NOT NULL, stake INTEGER NOT NULL DEFAULT 0, status TEXT NOT NULL DEFAULT 'pending', duel_id INTEGER NULL, expires_at INTEGER NOT NULL, winner_id INTEGER NULL);

CREATE TABLE IF NOT EXISTS tournaments(id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, size INTEGER NOT NULL DEFAULT 8, status TEXT NOT NULL DEFAULT 'announced', starts_at INTEGER NOT NULL, checkin_at INTEGER NOT NULL, created_by INTEGER NULL, winner_id INTEGER NULL);
CREATE TABLE IF NOT EXISTS tournament_players(tournament_id INTEGER NOT NULL, user_id INTEGER NOT NULL, seed INTEGER NOT NULL DEFAULT 0, checked_in INTEGER NOT NULL DEFAULT 0, eliminated_round INTEGER NULL, PRIMARY KEY(tournament_id, user_id));
CREATE TABLE IF NOT EXISTS tournament_matches(id INTEGER PRIMARY KEY AUTOINCREMENT, tournament_id INTEGER NOT NULL, round TEXT NOT NULL, slot INTEGER NOT NULL DEFAULT 0, p1_id INTEGER NULL, p2_id INTEGER NULL, winner_id INTEGER NULL, best_of INTEGER NOT NULL DEFAULT 1, p1_wins INTEGER NOT NULL DEFAULT 0, p2_wins INTEGER NOT NULL DEFAULT 0, due_at INTEGER NULL, status TEXT NOT NULL DEFAULT 'pending', duel_id INTEGER NULL);

CREATE TABLE IF NOT EXISTS audit_log(id INTEGER PRIMARY KEY AUTOINCREMENT, actor_id INTEGER NULL, action TEXT NOT NULL, target TEXT NULL, meta_json TEXT NULL, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS notifications(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, kind TEXT NOT NULL, text TEXT NOT NULL, action TEXT NULL, read_at INTEGER NULL, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS kv(k TEXT PRIMARY KEY, v TEXT NOT NULL);
